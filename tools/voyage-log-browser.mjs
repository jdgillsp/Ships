import puppeteer from 'puppeteer';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createGameServer } from '../server/index.mjs';
import { act, tick, BASE } from '../src/game/Simulation.js';

const app = createGameServer(); app.server.listen(0, '127.0.0.1');
await new Promise(resolve => app.server.once('listening', resolve));
const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox', '--use-angle=d3d11', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 800 } });
const out = 'tools/shots/voyage-log'; await fs.mkdir(out, { recursive: true });
try {
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${app.server.address().port}/?mode=expedition&preset=low&adaptive=0`);
  await page.waitForFunction(() => window.__app?.running && !document.getElementById('boot'), { timeout: 120000 });
  await page.click('#start-expedition'); await page.waitForFunction(() => window.__app.game.started && window.__app.game.net.ready && window.__app.game.lastMode === 'deck');
  await page.click('#crew-activities'); await page.click('#voyage-log summary');
  assert.equal(await page.$eval('#save-voyage-log', e => e.disabled), true);
  const { room, id } = await page.evaluate(() => ({ room: window.__app.game.net.room, id: window.__app.game.net.id }));
  const world = app.rooms.get(room).world;
  act(world, id, 'helm'); act(world, id, 'anchor'); world.ship.z = BASE.z - 40; tick(world);
  await page.waitForFunction(() => document.querySelector('#voyage-log ol').children.length === 1);
  const entry = await page.$eval('#voyage-log ol', e => e.textContent);
  assert.match(entry, /Left Pelican Station/);
  await page.keyboard.press('b'); assert.equal(world.ship.anchor, false, 'Notebook isolates anchor input');
  for (const width of [1280, 390]) {
    await page.setViewport({ width, height: 800 });
    await page.$eval('#voyage-log', e => e.scrollIntoView({ block: 'center' }));
    assert.ok(await page.$eval('#crew-activities-dialog', e => e.scrollWidth <= e.clientWidth));
    await page.screenshot({ path: `${out}/${width}.png` });
  }
  const client = await page.createCDPSession();
  await client.send('Page.setDownloadBehavior', { behavior: 'allow', downloadPath: (await import('node:path')).resolve(out) });
  await page.click('#save-voyage-log');
  const file = `${out}/kestrel-voyage-${world.seed}.txt`;
  for (let n = 0; n < 40; n++) { try { assert.match(await fs.readFile(file, 'utf8'), /Left Pelican Station/); break; } catch (e) { if (n === 39) throw e; await new Promise(r => setTimeout(r, 100)); } }
  await page.reload();
  await page.waitForFunction(() => window.__app?.running && !document.getElementById('boot'), { timeout: 120000 });
  await page.click('#start-expedition'); await page.waitForFunction(() => window.__app.game.started && window.__app.game.net.ready && window.__app.game.lastMode === 'deck');
  await page.click('#crew-activities'); await page.click('#voyage-log summary');
  assert.equal(await page.$eval('#voyage-log ol', e => e.textContent), entry);
  const anchorBeforeWriting = world.ship.anchor;
  await page.click('#crew-log-text'); await page.keyboard.type('A ray passed beneath the bow.\nReturn here at sunrise.');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('#crew-activities-dialog').open);
  await page.click('#crew-activities');
  assert.match(await page.$eval('#crew-log-text', e => e.value), /Return here at sunrise/);
  await page.click('#add-crew-log');
  await page.waitForFunction(() => document.querySelector('#voyage-log ol').textContent.includes('A ray passed beneath the bow.'));
  assert.equal(world.crewLog.length, 1); assert.equal(world.ship.anchor, anchorBeforeWriting, 'Typing the note does not operate the ship');
  await page.click('[data-log-location]');
  await page.waitForFunction(() => document.querySelector('[data-log-location]').textContent === 'Location saved in chart');
  assert.equal(Object.values(world.places).filter(p => p.sourceLog === world.crewLog[0].id).length, 1);
  const context = await browser.createBrowserContext(), peer = await context.newPage();
  await peer.goto(`http://127.0.0.1:${app.server.address().port}/?mode=expedition&preset=low&adaptive=0&room=${room}`);
  await peer.waitForFunction(() => window.__app?.running && !document.getElementById('boot'), { timeout: 120000 });
  await peer.click('#start-expedition'); await peer.waitForFunction(() => window.__app.game.net.ready);
  await peer.click('#crew-activities'); await peer.click('#voyage-log summary');
  assert.match(await peer.$eval('#voyage-log ol', e => e.textContent), /A ray passed beneath the bow/);
  await peer.click('#crew-log-text'); await peer.keyboard.type('I marked the channel for our next visit.'); await peer.click('#add-crew-log');
  await page.waitForFunction(() => document.querySelector('#voyage-log ol').textContent.includes('I marked the channel'));
  await page.bringToFront();
  await page.$eval('#crew-log-composer', e => e.scrollIntoView({ block: 'center' }));
  await page.screenshot({ path: `${out}/crew-entry-phone.png` });
  await page.reload();
  await page.waitForFunction(() => window.__app?.running && !document.getElementById('boot'), { timeout: 120000 });
  await page.click('#start-expedition'); await page.waitForFunction(() => window.__app.game.net.ready);
  assert.equal(await page.evaluate(() => window.__app.game.state.crewLog.length), 2);
  await page.keyboard.press('n'); await page.waitForFunction(() => document.querySelector('#voyage-chart').open);
  const destination = Object.values(world.places).find(p => p.sourceLog === world.crewLog[0].id).id;
  await page.select('#voyage-destination', destination);
  assert.match(await page.$eval('#voyage-description', e => e.textContent), /Return here at sunrise/);
  await page.click('#plot-course');
  await page.waitForFunction(id => window.__app.game.state.course?.id === id, {}, destination);
  await page.waitForFunction(() => !document.querySelector('#voyage-chart').open);
  await page.keyboard.press('v'); await page.waitForFunction(() => window.__app.game.lastMode === 'diver');
  await page.keyboard.down('ControlLeft');
  await page.waitForFunction(() => window.__app.game.state.players[window.__app.game.net.id].diveRecord?.maximumDepth > 5);
  await page.keyboard.up('ControlLeft');
  await page.keyboard.down('Space');
  await page.waitForFunction(() => window.__app.game.state.players[window.__app.game.net.id].y > -1);
  await page.keyboard.up('Space'); await page.keyboard.press('f');
  await page.waitForFunction(() => window.__app.game.lastMode === 'deck' && window.__app.game.state.diveRecords?.length === 1);
  await page.click('#crew-activities');
  await page.$eval('#voyage-log', e => { e.open = true; e.scrollIntoView({ block: 'center' }); });
  await page.waitForFunction(() => document.querySelector('#voyage-log ol').textContent.includes('maximum depth'));
  assert.match(await page.$eval('#voyage-log ol', e => e.textContent), /Climbed aboard/);
  await page.screenshot({ path: `${out}/completed-dive-phone.png` });
  const totalEntries = await page.$$eval('#voyage-log ol li', rows => rows.length);
  await page.click('#search-voyage-log'); await page.keyboard.type('CHANNEL next');
  assert.equal(await page.$$eval('#voyage-log ol li', rows => rows.length), 1);
  assert.match(await page.$eval('#voyage-log ol', e => e.textContent), /I marked the channel/);
  assert.match(await page.$eval('#voyage-search-count', e => e.textContent), /1 of/);
  await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.querySelector('#crew-activities-dialog').open);
  await page.click('#crew-activities');
  assert.equal(await page.$eval('#search-voyage-log', e => e.value), 'CHANNEL next');
  await page.click('#search-voyage-log'); await page.keyboard.down('Control'); await page.keyboard.press('a'); await page.keyboard.up('Control'); await page.keyboard.type('no matching memory');
  assert.equal(await page.$$eval('#voyage-log ol li', rows => rows.length), 0);
  assert.equal(await page.$eval('#save-voyage-log', e => e.disabled), false, 'Filtering does not prevent exporting the full log');
  await page.screenshot({ path: `${out}/search-phone.png` });
  await page.click('#clear-voyage-search');
  assert.equal(await page.$$eval('#voyage-log ol li', rows => rows.length), totalEntries);
  assert.deepEqual(errors, []);
  console.log('Voyage log: live update, empty state, input isolation, desktop/phone layout, download and rejoin passed.');
} finally { await browser.close(); await app.stop(); }
