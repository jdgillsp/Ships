import puppeteer from 'puppeteer';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createGameServer } from '../server/index.mjs';
import * as simulation from '../src/game/Simulation.js';
import { voyageSites } from '../src/game/VoyageSites.js';
import { stormAfter } from '../src/game/WeatherOutlook.js';

// Hold the scenario clock while comparing plans. Forecast/server time agreement
// is covered separately by the simulation test running 2,400 real ticks.
const app = createGameServer({ ...simulation, tick() {} }); app.server.listen(0, '127.0.0.1');
await new Promise(r => app.server.once('listening', r));
const base = `http://127.0.0.1:${app.server.address().port}`;
const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox', '--use-angle=d3d11', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 800 } });
const out = 'tools/shots/weather-planner'; await fs.mkdir(out, { recursive: true });
try {
  const page = await browser.newPage(), errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/?mode=expedition&preset=low&adaptive=0`);
  await page.waitForFunction(() => window.__app?.running && !document.getElementById('boot'), { timeout: 120000 });
  await page.click('#start-expedition'); await page.waitForFunction(() => window.__app.game.started && window.__app.game.net.ready);
  const { room, id } = await page.evaluate(() => ({ room: window.__app.game.net.room, id: window.__app.game.net.id }));
  const world = app.rooms.get(room).world, reef = voyageSites().find(s => s.id === 'reef');
  const setClock = time => { world.time = time; for (const p of Object.values(world.players)) p.lastInput = time; };
  const post = async (path, body, token) => {
    const response = await fetch(`${base}/api/rooms/${room}/${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: JSON.stringify(body) });
    assert.ok(response.ok); return response.json();
  };
  const peer = await post('join', { name: 'Rowan' });
  await page.keyboard.press('n'); await page.waitForSelector('#voyage-chart[open]');
  assert.match(await page.$eval('#planned-weather', e => e.textContent), /No timed outlook/);
  Object.assign(world.ship, { x: reef.x, z: reef.z }); Object.assign(world, { stormStart: 0, time: 0, mission: 'dive', storm: 0 });
  await page.waitForFunction(() => document.querySelector('#weather-outlook').textContent.includes('approaching'));
  await page.select('#planned-stay', '30');
  await page.waitForFunction(() => document.querySelector('#planned-weather').textContent.includes('fair on surfacing'));
  const short = await page.$eval('#planned-surface', e => e.textContent);
  await page.select('#planned-stay', '300');
  assert.match(await page.$eval('#planned-weather', e => e.textContent), /rough on surfacing/);
  assert.notEqual(await page.$eval('#planned-surface', e => e.textContent), short);
  await page.select('#voyage-destination', 'deep');
  assert.match(await page.$eval('#planned-weather', e => e.textContent), /rough on arrival/);
  for (const width of [1280, 390]) {
    await page.setViewport({ width, height: 800 }); await page.$eval('#dive-planner', e => e.scrollIntoView({ block: 'center' }));
    assert.ok(await page.$eval('#voyage-chart', e => e.scrollWidth <= e.clientWidth));
    await page.screenshot({ path: `${out}/plan-${width}.png` });
  }
  await page.click('#plan-salvage');
  await page.select('#planned-stay', '30');
  assert.equal(await page.$eval('#salvage-return-plan', e => e.hidden), false);
  const shortReturn = await page.$eval('#planned-home', e => e.textContent);
  await page.select('#planned-stay', '300');
  assert.notEqual(await page.$eval('#planned-home', e => e.textContent), shortReturn);
  assert.match(await page.$eval('#planned-home-weather', e => e.textContent), /Rough/);
  world.cargo.attached = true; world.mission = 'recovery';
  await page.waitForFunction(() => document.querySelector('#planned-stay').hidden);
  assert.match(await page.$eval('#planned-boarding', e => e.textContent), /0 sec/);
  await page.$eval('#salvage-return-plan', e => e.scrollIntoView({ block: 'center' }));
  await page.screenshot({ path: `${out}/salvage-return-phone.png` });
  await page.select('#voyage-destination', 'deep');
  assert.equal(await page.$eval('#salvage-return-plan', e => e.hidden), true);
  await page.click('#plan-home');
  assert.equal(await page.$eval('#voyage-name', e => e.textContent), 'Pelican Station');
  assert.match(await page.$eval('#voyage-depth', e => e.textContent), /Surface destination/);
  assert.equal(await page.$eval('#planned-stay', e => e.hidden), true);
  assert.doesNotMatch(await page.$eval('#voyage-record', e => e.textContent), /survey/i);
  await page.screenshot({ path: `${out}/homeward-phone.png` });
  await page.click('#plot-course'); await page.waitForSelector('#voyage-chart:not([open])');
  await post('action', { action: 'dive' }, peer.token);
  await page.waitForFunction(() => document.querySelector('#mission-detail').textContent.includes('Recover the dive team'));
  await post('action', { action: 'rescue' }, peer.token);
  await page.waitForFunction(() => document.querySelector('#mission-detail').textContent.includes('homeward course'));
  await page.keyboard.press('n'); await page.waitForSelector('#voyage-chart[open]');
  await page.select('#voyage-destination', 'deep');
  Object.assign(world, { mission: 'complete', storm: .85 });
  await page.waitForFunction(() => document.querySelector('#weather-outlook').textContent.includes('easing'));
  assert.match(await page.$eval('#planned-weather', e => e.textContent), /fair on surfacing/);
  // Completed fixtures do not interrupt the explicit radio interaction with a receipt.
  await page.evaluate(() => { window.__app.game.completed = true; });
  await page.keyboard.press('Escape'); await page.waitForSelector('#voyage-chart:not([open])');
  await page.keyboard.press('z'); await page.waitForSelector('#crew-radio-dialog[open]');
  await page.click('#call-weather'); await page.waitForSelector('#crew-radio-dialog:not([open])');
  await page.waitForFunction(() => document.querySelector('#crew-call-banner').textContent.includes('squall easing'));
  const call = structuredClone(world.calls[id]); assert.match(call.outlook, /squall easing/);
  await post('action', { action: 'acknowledgeCall', owner: id, callId: call.id }, peer.token);
  await page.waitForFunction(() => document.querySelector('#crew-call-banner').textContent.includes('Rowan: On it'));
  assert.equal(world.ship.pilot, null); assert.equal(world.ship.anchor, true);
  Object.assign(world, { explorationWeather: { time: 0, storm: .85 }, storm: 0 }); setClock(390);
  Object.assign(world.ship, { x: reef.x, z: reef.z });
  await page.keyboard.press('n'); await page.waitForSelector('#voyage-chart[open]'); await page.select('#voyage-destination', 'reef');
  await page.waitForFunction(() => document.querySelector('#weather-outlook').textContent.includes('front approaching'));
  await page.select('#planned-stay', '30'); assert.match(await page.$eval('#planned-weather', e => e.textContent), /fair on surfacing/);
  await page.select('#planned-stay', '180'); assert.match(await page.$eval('#planned-weather', e => e.textContent), /rough on surfacing/);
  await page.$eval('#dive-planner', e => e.scrollIntoView({ block: 'center' }));
  await page.screenshot({ path: `${out}/front-plan-phone.png` });
  await page.keyboard.press('Escape'); await page.keyboard.press('z'); await page.waitForSelector('#crew-radio-dialog[open]');
  await page.click('#call-weather'); await page.waitForSelector('#crew-radio-dialog:not([open])');
  await page.waitForFunction(() => document.querySelector('#crew-call-banner').textContent.includes('front approaching'));
  const frontCall = structuredClone(world.calls[id]);
  setClock(560); world.storm = stormAfter(world);
  await page.waitForFunction(() => window.__app.weather.state.storm > .5 && window.__app.weather.state.rain > .3 && window.__app.rain.geom.instanceCount > 0);
  await page.setViewport({ width: 1280, height: 800 }); await page.keyboard.press('h');
  await page.waitForFunction(() => window.__app.game.lastMode === 'helm');
  if (await page.evaluate(() => window.__app.game.view !== 'chase')) await page.keyboard.press('c');
  await page.evaluate(async () => { for (let n = 0; n < 40; n++) await new Promise(requestAnimationFrame); });
  await page.screenshot({ path: `${out}/passing-front.png` });
  setClock(700); world.storm = stormAfter(world);
  await page.keyboard.press('n'); await page.waitForSelector('#voyage-chart[open]');
  await page.waitForFunction(() => document.querySelector('#weather-outlook').textContent.includes('front easing'));
  assert.match(await page.$eval('#weather-outlook', e => e.textContent), /fair in 2 min/);
  await page.keyboard.press('Escape'); setClock(800); world.storm = stormAfter(world);
  await page.waitForFunction(() => window.__app.weather.state.storm === 0 && window.__app.weather.state.rain === 0);
  await page.evaluate(async () => { for (let n = 0; n < 40; n++) await new Promise(requestAnimationFrame); });
  await page.screenshot({ path: `${out}/front-cleared.png` });
  assert.deepEqual(world.calls[id], frontCall, 'The sent weather report is a snapshot, not a changing forecast');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ shortAndLongPlans: true, destinationChanges: true, unknownWeather: true, clearing: true, passingExplorationFront: true, renderedRainAndClearing: true, phoneLayout: true, nativeWeatherCall: true, peerAcknowledgement: true, errors }));
} finally { await browser.close(); await app.stop(); }
